/* ============================================================
   I18n Helpers
   ============================================================ */

let currentLang = 'zh';

function t(key) {
  return i18n[currentLang][key] || i18n.zh[key] || key;
}

function setLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  localStorage.setItem('aurora-lang', lang);

  // Update all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translated = t(key);
    if (translated && translated !== key) {
      el.textContent = translated;
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translated = t(key);
    if (translated && translated !== key) {
      el.placeholder = translated;
    }
  });

  // Update title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translated = t(key);
    if (translated && translated !== key) {
      el.title = translated;
    }
  });

  // Update nav lang button
  const langBtn = document.getElementById('nav-lang');
  if (langBtn) {
    langBtn.textContent = lang === 'zh' ? 'EN' : '中文';
  }

  // Update page title
  const pageTitle = document.querySelector('title');
  if (pageTitle && pageTitle.hasAttribute('data-i18n')) {
    pageTitle.textContent = t(pageTitle.getAttribute('data-i18n'));
  }
}

function toggleLang() {
  setLang(currentLang === 'zh' ? 'en' : 'zh');
}

// Init on DOM ready
document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('aurora-lang');
  const urlLang = new URLSearchParams(window.location.search).get('lang');
  const initialLang = urlLang || saved || 'zh';
  setLang(initialLang);
});
